%% ============================================================
% EXPERIMENT 2 - SELECTION RELEVANCE AND OUTLIER ROBUSTNESS
%
% Repository location:
%   experiments/run_experiment2_selection_robustness.m
%
% This script computes NUMERICAL RESULTS ONLY.
% It does not generate paper figures.
%
% PART A - Selection relevance
%   - fixed subset size K from current nominal FA/BE result
%   - 50,000 random K-subsets
%   - FA, BE, top-C/N0, and top-elevation references
%
% PART B - Robustness to impulsive pseudorange outliers
%   - N_out = {0,2,4,6}
%   - 10,000 Monte Carlo trials per case
%   - full-pool WLS
%   - residual rejection + FA
%   - residual rejection + BE
%   - exact-detection + feasible conditional RMSE
%
% Current notation:
%   FA = Forward Adding
%   BE = Backward Elimination
%   N_out = number of outliers
%
% Compatibility:
%   The robustness MAT file also contains Tpost with legacy
%   FTS/BTS variable names expected by the already-tuned plot.
%
% Required inputs:
%   results/candidate_pool_26.mat
%   results/link_budget.mat
%   results/FA_results.mat
%   results/BE_results.mat
%
% Outputs:
%   results/experiment2_selection_robustness/
%       selection_necessity_methods.csv
%       selection_necessity_random_summary.csv
%       selection_necessity_random_subsets.csv
%       selection_necessity_results.mat
%
%       experiment2_robust_summary.csv
%       experiment2_robust_trials.csv
%       experiment2_robust_results.mat
%       experiment2_robust_postprocessed.mat
%
%       experiment2_results.mat
%
% Reproducibility:
%   rng(2,'twister')
% ============================================================

