%% ============================================================
% PRECOMPUTE BEST 4-TX INITIALIZATION FOR ROBUST FA
%
% All 4-combinations and their bounds are fixed because geometry
% and nominal covariance are fixed at the nominal epoch.
% For a retained candidate set, the best feasible 4-set is the
% first globally sorted 4-set fully contained in that retained set.
% =============================================================

fprintf('\n');
fprintf('Precomputing all 4-transmitter initialization bounds...\n');

comb4 = ...
    nchoosek(1:Npool,4);

nComb4 = ...
    size(comb4,1);

comb4Bound = ...
    inf(nComb4,1);

for q = 1:nComb4

    [b,~,rk] = ...
        subsetMetrics( ...
            comb4(q,:), ...
            Hfull, ...
            sigmaRho_m);

    if rk==4
        comb4Bound(q) = b;
    end
end

[~,comb4Order] = ...
    sort(comb4Bound,'ascend');

comb4Sorted = ...
    comb4(comb4Order,:);

fprintf('Precomputed %d four-transmitter subsets.\n',nComb4);

%% ============================================================
% PART B - OUTLIER ROBUSTNESS
% =============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('PART B - OUTLIER ROBUSTNESS\n');
fprintf('============================================================\n');

N_MC = 10000;
% N_MC = 100;

N_out_values = ...
    [0 2 4 6];

outlierLowerSigma = 20;
outlierUpperSigma = 100;

initialOffset_m = ...
    [100;-100;50];

theta0 = [ ...
    UserPositionECEF + initialOffset_m; ...
    0];

maxWLSIterations = 30;
wlsTolerance_m = 1e-6;

% Restart deterministic random stream for Part B.
rng(2,'twister');

nCases = ...
    numel(N_out_values);

nTrials = ...
    nCases*N_MC;

%% Preallocate per-trial outputs

TrialID = zeros(nTrials,1);
N_out_column = zeros(nTrials,1);

ErrorNoSelection_m = nan(nTrials,1);
ErrorFA_m = nan(nTrials,1);
ErrorBE_m = nan(nTrials,1);

KfinalFA = nan(nTrials,1);
KfinalBE = nan(nTrials,1);

FinalBoundFA_m = nan(nTrials,1);
FinalBoundBE_m = nan(nTrials,1);

FAFeasible = false(nTrials,1);
BEFeasible = false(nTrials,1);

FAEvaluations = nan(nTrials,1);
BEEvaluations = nan(nTrials,1);

CorrectOutliers = nan(nTrials,1);
DetectionRate = nan(nTrials,1);
ExactDetection = false(nTrials,1);
RejectionCompleted = false(nTrials,1);

WLSNoSelectionConverged = false(nTrials,1);
WLSFAConverged = false(nTrials,1);
WLSBEConverged = false(nTrials,1);

trialRow = 0;

%% Monte Carlo

for icase = 1:nCases

    N_out = ...
        N_out_values(icase);

    fprintf('\n');
    fprintf('------------------------------------------------------------\n');
    fprintf('Running N_out = %d\n',N_out);
    fprintf('------------------------------------------------------------\n');

    for mc = 1:N_MC

        trialRow = ...
            trialRow + 1;

        %% Nominal Gaussian noise

        gaussianNoise = ...
            sigmaRho_m .* randn(Npool,1);

        %% Sparse impulsive contamination

        impulsiveComponent = ...
            zeros(Npool,1);

        trueOutlierIdx = ...
            zeros(0,1);

        if N_out > 0

            trueOutlierIdx = ...
                randperm(Npool,N_out).';

            multipliers = ...
                balancedOutlierMultipliers( ...
                    N_out, ...
                    outlierLowerSigma, ...
                    outlierUpperSigma);

            multipliers = ...
                multipliers(randperm(N_out));

            impulsiveComponent(trueOutlierIdx) = ...
                multipliers(:) .* ...
                sigmaRho_m(trueOutlierIdx);
        end

        measurementError = ...
            gaussianNoise + ...
            impulsiveComponent;

        rhoMeasured_m = ...
            rhoTrue_m + measurementError;

        %% ----------------------------------------------------
        % No selection: full-pool WLS
        %% ----------------------------------------------------

        [thetaFull,~,~,convFull] = ...
            iterativeWLS( ...
                rhoMeasured_m, ...
                PositionECEF, ...
                sigmaRho_m, ...
                theta0, ...
                maxWLSIterations, ...
                wlsTolerance_m);

        errFull = ...
            norm( ...
                thetaFull(1:3) ...
                - UserPositionECEF);

        %% ----------------------------------------------------
        % Common residual-aided rejection stage
        %% ----------------------------------------------------

        active = ...
            (1:Npool).';

        removedByResidual = ...
            zeros(0,1);

        for jj = 1:N_out

            rhoActive = ...
                rhoMeasured_m(active);

            posActive = ...
                PositionECEF(active,:);

            sigActive = ...
                sigmaRho_m(active);

            [~,residualActive,Hactive,~] = ...
                iterativeWLS( ...
                    rhoActive, ...
                    posActive, ...
                    sigActive, ...
                    theta0, ...
                    maxWLSIterations, ...
                    wlsTolerance_m);

            normalizedResidual = ...
                computeNormalizedResidual( ...
                    residualActive, ...
                    Hactive, ...
                    sigActive);

            [~,order] = ...
                sort( ...
                    normalizedResidual, ...
                    'descend');

            removedThisStep = NaN;

            for qq = 1:numel(order)

                localCandidate = ...
                    order(qq);

                globalCandidate = ...
                    active(localCandidate);

                trialActive = ...
                    active( ...
                    active~=globalCandidate);

                if numel(trialActive) < 4
                    continue;
                end

                if rank(Hfull(trialActive,:)) < 4
                    continue;
                end

                removedThisStep = ...
                    globalCandidate;

                break;
            end

            if isnan(removedThisStep)
                break;
            end

            active( ...
                active==removedThisStep) = [];

            removedByResidual(end+1,1) = ...
                removedThisStep; %#ok<AGROW>
        end

        rejectionCompleted = ...
            numel(removedByResidual)==N_out;

        %% Detection metrics

        if N_out==0

            nCorrect = 0;
            detectionRate = 1;
            exactDetection = true;

        else

            nCorrect = ...
                numel( ...
                    intersect( ...
                        trueOutlierIdx, ...
                        removedByResidual));

            detectionRate = ...
                nCorrect/N_out;

            exactDetection = ...
                rejectionCompleted && ...
                isequal( ...
                    sort(removedByResidual), ...
                    sort(trueOutlierIdx));
        end

        %% ----------------------------------------------------
        % Residual-aided FA
        %% ----------------------------------------------------

        [ ...
            selectedRobustFA, ...
            boundRobustFA, ...
            ~, ...
            evalFA, ...
            feasibleFA] = ...
            forwardAddingRetained( ...
                active, ...
                Hfull, ...
                sigmaRho_m, ...
                target_m, ...
                targetTol, ...
                comb4Sorted);

        [thetaFA,~,~,convFA] = ...
            iterativeWLS( ...
                rhoMeasured_m(selectedRobustFA), ...
                PositionECEF(selectedRobustFA,:), ...
                sigmaRho_m(selectedRobustFA), ...
                theta0, ...
                maxWLSIterations, ...
                wlsTolerance_m);

        errFA = ...
            norm( ...
                thetaFA(1:3) ...
                - UserPositionECEF);

        %% ----------------------------------------------------
        % Residual-aided BE
        %% ----------------------------------------------------

        [ ...
            selectedRobustBE, ...
            boundRobustBE, ...
            ~, ...
            evalBE, ...
            feasibleBE] = ...
            backwardEliminationRetained( ...
                active, ...
                Hfull, ...
                sigmaRho_m, ...
                target_m, ...
                targetTol);

        [thetaBE,~,~,convBE] = ...
            iterativeWLS( ...
                rhoMeasured_m(selectedRobustBE), ...
                PositionECEF(selectedRobustBE,:), ...
                sigmaRho_m(selectedRobustBE), ...
                theta0, ...
                maxWLSIterations, ...
                wlsTolerance_m);

        errBE = ...
            norm( ...
                thetaBE(1:3) ...
                - UserPositionECEF);

        %% Store

        TrialID(trialRow) = mc;
        N_out_column(trialRow) = N_out;

        ErrorNoSelection_m(trialRow) = errFull;
        ErrorFA_m(trialRow) = errFA;
        ErrorBE_m(trialRow) = errBE;

        KfinalFA(trialRow) = ...
            numel(selectedRobustFA);

        KfinalBE(trialRow) = ...
            numel(selectedRobustBE);

        FinalBoundFA_m(trialRow) = ...
            boundRobustFA;

        FinalBoundBE_m(trialRow) = ...
            boundRobustBE;

        FAFeasible(trialRow) = ...
            feasibleFA;

        BEFeasible(trialRow) = ...
            feasibleBE;

        FAEvaluations(trialRow) = ...
            evalFA;

        BEEvaluations(trialRow) = ...
            evalBE;

        CorrectOutliers(trialRow) = ...
            nCorrect;

        DetectionRate(trialRow) = ...
