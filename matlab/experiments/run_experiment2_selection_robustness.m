function [alphaCRB_m,PDOP,rankH] = ...
    subsetMetrics(idx,Hfull,sigmaRho_m)

    idx = idx(:);

    H = ...
        Hfull(idx,:);

    sigma = ...
        sigmaRho_m(idx);

    rankH = ...
        rank(H);

    alphaCRB_m = inf;
    PDOP = inf;

    if rankH < 4
        return;
    end

    A = H.'*H;

    if rcond(A) > 1e-14

        Cgeom = ...
            A\eye(4);

        trGeom = ...
            trace(Cgeom(1:3,1:3));

        if trGeom>0 && isfinite(trGeom)
            PDOP = sqrt(trGeom);
        end
    end

    R = ...
        diag(sigma.^2);

    J = ...
        H.'*(R\H);

    if rcond(J) <= 1e-14
        return;
    end

    C = ...
        J\eye(4);

    trPos = ...
        trace(C(1:3,1:3));

    if trPos>0 && isfinite(trPos)
        alphaCRB_m = sqrt(trPos);
    end
end

function p = ...
    empiricalPercentile(x,percent)

    x = ...
        sort(x(isfinite(x)));

    x = x(:);

    if isempty(x)
        p = NaN;
        return;
    end

    if numel(x)==1
        p = x;
        return;
    end

    pos = ...
        1 + ...
        (numel(x)-1)*(percent/100);

    lo = floor(pos);
    hi = ceil(pos);

    if lo==hi

        p = x(lo);

    else

        w = ...
            pos-lo;

        p = ...
            (1-w)*x(lo) ...
            + w*x(hi);
    end
end

function multipliers = ...
    balancedOutlierMultipliers( ...
        N_out, ...
        lowerSigma, ...
        upperSigma)

    if N_out==0
        multipliers = zeros(0,1);
        return;
    end

    nPairs = ...
        floor(N_out/2);

    positive = ...
        lowerSigma ...
        + (upperSigma-lowerSigma) ...
        .* rand(nPairs,1);

    negative = ...
        -positive;

    multipliers = ...
        [positive;negative];

    if mod(N_out,2)==1

        extraMagnitude = ...
            lowerSigma ...
            + (upperSigma-lowerSigma)*rand;

        if rand<0.5
            extraMagnitude = -extraMagnitude;
        end

        multipliers = ...
            [multipliers;extraMagnitude]; %#ok<AGROW>
    end
end

function [theta,residual,H,converged] = ...
    iterativeWLS( ...
        rho_m, ...
        txECEF, ...
        sigma_m, ...
        theta0, ...
        maxIter, ...
        tol)

    theta = ...
        theta0(:);

    converged = false;

    rho_m = rho_m(:);
    sigma_m = sigma_m(:);

    for iter = 1:maxIter

        p = ...
            theta(1:3).';

        b = ...
            theta(4);

        diff = ...
            txECEF-p;

        ranges = ...
            sqrt(sum(diff.^2,2));

        if any(ranges<=eps)
            break;
        end

        u = ...
            diff./ranges;

        predicted = ...
            ranges+b;

        residual = ...
            rho_m-predicted;

        H = ...
            [-u,ones(size(txECEF,1),1)];

        Hw = ...
            H./sigma_m;

        rw = ...
            residual./sigma_m;

        Nmat = ...
            Hw.'*Hw;

        if rcond(Nmat)<=1e-14
            break;
        end

        delta = ...
            Nmat\(Hw.'*rw);

        theta = ...
            theta+delta;

        if norm(delta(1:3))<=tol && ...
           abs(delta(4))<=tol

            converged = true;
            break;
        end
    end

    p = theta(1:3).';
    b = theta(4);

    diff = txECEF-p;

    ranges = ...
        sqrt(sum(diff.^2,2));

    u = ...
        diff./ranges;

    predicted = ...
        ranges+b;

    residual = ...
        rho_m-predicted;

    H = ...
        [-u,ones(size(txECEF,1),1)];
end

function z = ...
    computeNormalizedResidual( ...
        residual, ...
        H, ...
        sigma_m)

    residual = ...
        residual(:);

    sigma_m = ...
        sigma_m(:);

    R = ...
        diag(sigma_m.^2);

    J = ...
        H.'*(R\H);

    if rcond(J)<=1e-14

        z = ...
            abs(residual)./sigma_m;

        return;
    end

    C = ...
        J\eye(4);

    Qv = ...
        R - H*C*H.';

    qdiag = ...
        real(diag(Qv));

    floorVar = ...
        max( ...
            1e-14, ...
            1e-12*median(sigma_m.^2));

    qdiag = ...
        max(qdiag,floorVar);

    z = ...
        abs(residual) ...
        ./ sqrt(qdiag);
end

function [ ...
    selected, ...
    finalBound, ...
    finalPDOP, ...
    evaluationCount, ...
    feasible] = ...
    forwardAddingRetained( ...
        active, ...
        Hfull, ...
        sigmaRho_m, ...
        target_m, ...
        targetTol, ...
        comb4Sorted)

    active = ...
        active(:).';

    Nactive = ...
        numel(active);

    evaluationCount = ...
        nchoosek(Nactive,4);

    activeMask = ...
        false(1,size(Hfull,1));

    activeMask(active) = true;

    selected = [];

    for q = 1:size(comb4Sorted,1)

        c4 = ...
            comb4Sorted(q,:);

        if all(activeMask(c4))

            selected = ...
                c4;

            break;
        end
    end

    if isempty(selected)

        finalBound = inf;
        finalPDOP = inf;
        feasible = false;
        return;
    end

    [currentBound,~,~] = ...
        subsetMetrics( ...
            selected, ...
            Hfull, ...
            sigmaRho_m);

    while currentBound > target_m+targetTol && ...
          numel(selected)<Nactive

        remaining = ...
            setdiff( ...
                active, ...
                selected, ...
                'stable');

        bestCandidate = NaN;
        bestBound = inf;

        for jj = 1:numel(remaining)

            trial = ...
                [selected,remaining(jj)];

            [b,~,rk] = ...
                subsetMetrics( ...
                    trial, ...
                    Hfull, ...
                    sigmaRho_m);

            evaluationCount = ...
                evaluationCount+1;

            if rk==4 && b<bestBound

                bestBound = b;
                bestCandidate = remaining(jj);
            end
        end

        if isnan(bestCandidate)
            break;
        end

        selected(end+1) = ...
            bestCandidate; %#ok<AGROW>

        currentBound = ...
            bestBound;
    end

    [finalBound,finalPDOP,rankH] = ...
        subsetMetrics( ...
            selected, ...
            Hfull, ...
            sigmaRho_m);

    feasible = ...
        rankH==4 && ...
        finalBound<=target_m+targetTol;
end

function [ ...
    selected, ...
    finalBound, ...
    finalPDOP, ...
    evaluationCount, ...
    feasible] = ...
    backwardEliminationRetained( ...
        active, ...
        Hfull, ...
        sigmaRho_m, ...
        target_m, ...
        targetTol)

    selected = ...
        active(:).';

    evaluationCount = 0;

    [fullBound,fullPDOP,fullRank] = ...
        subsetMetrics( ...
            selected, ...
            Hfull, ...
            sigmaRho_m);

    if fullRank<4 || ...
       fullBound>target_m+targetTol

        finalBound = fullBound;
        finalPDOP = fullPDOP;
        feasible = false;
        return;
    end

    while numel(selected)>4

        bestRemoved = NaN;
        bestBound = inf;

        for jj = 1:numel(selected)

            candidate = ...
                selected(jj);

            trial = ...
                selected( ...
                    selected~=candidate);

            [b,~,rk] = ...
                subsetMetrics( ...
                    trial, ...
                    Hfull, ...
                    sigmaRho_m);

            evaluationCount = ...
                evaluationCount+1;

            if rk~=4
                continue;
            end

            if b>target_m+targetTol
                continue;
            end

            if b<bestBound

                bestBound = b;
                bestRemoved = candidate;

            elseif abs(b-bestBound)<=1e-14

                if isnan(bestRemoved) || ...
                   candidate<bestRemoved

                    bestBound = b;
                    bestRemoved = candidate;
                end
            end
        end

        if isnan(bestRemoved)
            break;
        end

        selected( ...
            selected==bestRemoved) = [];
    end

    [finalBound,finalPDOP,rankH] = ...
        subsetMetrics( ...
            selected, ...
            Hfull, ...
            sigmaRho_m);

    feasible = ...
        rankH==4 && ...
        finalBound<=target_m+targetTol;
end
