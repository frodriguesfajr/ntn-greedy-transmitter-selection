%% Atmospheric quantities

theta = 300/T_K;

e = rho_gm3*T_K/216.7;       % water-vapour partial pressure
p = max(P_hPa-e,0);           % dry-air pressure

%% Oxygen

fo = O(:,1);
a1 = O(:,2);
a2 = O(:,3);
a3 = O(:,4);
a4 = O(:,5);
a5 = O(:,6);
a6 = O(:,7);

So = a1*1e-7 .* p .* theta^3 .* ...
    exp(a2*(1-theta));

dfo = a3*1e-4 .* ...
    (p.*theta.^(0.8-a4) + 1.1*e*theta);

dfo = sqrt(dfo.^2 + 2.25e-6);

delta = (a5+a6*theta)*1e-4 .* ...
    (p+e).*theta^0.8;

Fo = (f./fo) .* ( ...
    (dfo-delta.*(fo-f))./((fo-f).^2+dfo.^2) + ...
    (dfo-delta.*(fo+f))./((fo+f).^2+dfo.^2));

%% Dry continuum

d = 5.6e-4*(p+e)*theta^0.8;

Nd = f*p*theta^2 * ( ...
    6.14e-5/(d*(1+(f/d)^2)) + ...
    1.4e-12*p*theta^1.5/(1+1.9e-5*f^1.5));

NO = sum(So.*Fo) + Nd;

%% Water vapour

fw = W(:,1);
b1 = W(:,2);
b2 = W(:,3);
b3 = W(:,4);
b4 = W(:,5);
b5 = W(:,6);
b6 = W(:,7);

Sw = b1*1e-1 .* e .* theta^3.5 .* ...
    exp(b2*(1-theta));

dfw = b3*1e-4 .* ...
    (p.*theta.^b4 + b5.*e.*theta.^b6);

dfw = 0.535*dfw + sqrt( ...
    0.217*dfw.^2 + ...
    2.1316e-12*fw.^2/theta);

Fw = (f./fw) .* ( ...
    dfw./((fw-f).^2+dfw.^2) + ...
    dfw./((fw+f).^2+dfw.^2));

NW = sum(Sw.*Fw);

%% Specific attenuation

gammaO_dBkm = 0.1820*f*NO;
gammaW_dBkm = 0.1820*f*NW;

gamma_dBkm = gammaO_dBkm + gammaW_dBkm;

